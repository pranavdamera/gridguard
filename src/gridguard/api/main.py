"""
GridGuard FastAPI backend.

Endpoints:
  GET  /health              — system status + calibration state
  GET  /sites               — all configured DMV sites
  GET  /sites/{site_id}     — single site detail
  GET  /forecast            — predict generation for a time window
  POST /forecast            — predict for a single interval (legacy)
  GET  /anomalies           — list anomalous intervals
  GET  /events              — anomaly intervals grouped into events
  GET  /events/{event_id}   — single event detail
  GET  /explain             — SHAP contributors for a timestamp
  GET  /metrics             — model comparison table
  GET  /demo/scenario       — the scripted June 15 GMU demo event

Run locally:
    uvicorn gridguard.api.main:app --reload --port 8000

Design notes:
  - Models and test data are loaded once at startup (lifespan event).
  - Residual calibration stats are loaded from artifacts/models/residual_stats.json
    (generated by 'make demo-reset') so anomaly thresholds are never contaminated
    by test-set statistics.
  - No database — state lives in memory for the demo.
  - CORS origins are controlled by the ALLOWED_ORIGINS environment variable.
"""

