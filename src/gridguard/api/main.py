logger = logging.getLogger(__name__)

# ---------------------------------------------------------------------------
# App state — loaded once at startup
# ---------------------------------------------------------------------------

_state: dict = {
    "models": {},           # lag-aware forecasting models (for /forecast, /metrics)
    "anomaly_model": None,  # weather-only anomaly detector (for /anomalies, /events)
    "test_df": None,
    "anomaly_df": None,
    "events_df": None,
    "metrics_df": None,
    "best_model_name": "xgboost",
    "residual_stats": None,
}


@asynccontextmanager
async def lifespan(app: FastAPI):
    """Load models, calibration stats, and pre-compute anomalies on startup."""
    logger.info("Loading artifacts …")

    model_dir = Path(settings.model_dir)
    processed_dir = Path(settings.data_processed_dir)

    _state["residual_stats"] = _load_residual_stats(model_dir)
    if _state["residual_stats"]:
        logger.info("Loaded residual calibration stats (%d hour buckets)", len(_state["residual_stats"]))
    else:
        logger.warning("No residual_stats.json found — run 'make demo-reset' first.")

    if not model_dir.exists():
        logger.warning("No model artifacts found. Run 'make demo-reset' first.")
        yield
        return

    from gridguard.models.baseline import ALL_MODELS

    # Load lag-aware forecasting models (for /forecast and /metrics)
    for name in ALL_MODELS:
        try:
            _state["models"][name] = load_model(name)
            logger.info("Loaded forecasting model: %s", name)
        except FileNotFoundError:
            logger.warning("Forecasting model not found: %s (skip)", name)

    # Load the dedicated weather-only anomaly detector (for /anomalies and /events).
    # This model is trained WITHOUT lag features so it can't mask persistent degradation.
    try:
        _state["anomaly_model"] = load_model("anomaly_detector")
        logger.info("Loaded anomaly_detector (weather-only, healthy-data trained)")
    except FileNotFoundError:
        logger.warning(
            "anomaly_detector.pkl not found — run 'make demo-reset'. "
            "Falling back to best forecasting model (lag leakage risk)."
        )
        # Graceful fallback so the API starts in environments without artifacts
        _state["anomaly_model"] = (
            _state["models"].get("xgboost")
            or next(iter(_state["models"].values()), None)
        )

    test_path = processed_dir / "test_df.parquet"

    if test_path.exists():
        test_df = pd.read_parquet(test_path)
        _state["test_df"] = test_df

        anomaly_model = _state["anomaly_model"]
        if anomaly_model is not None:
            _state["anomaly_df"] = detect_anomalies(
                test_df,
                anomaly_model,
                residual_stats=_state["residual_stats"],
            )
            _state["events_df"] = group_anomaly_events(_state["anomaly_df"])

        # Metrics compare all lag-aware forecasting models on the held-out test set
        if _state["models"]:
            X_test, y_test = get_X_y(test_df)
            forecast_models = {k: v for k, v in _state["models"].items() if k != "persistence" or True}
            _state["metrics_df"] = compare_models(forecast_models, X_test, y_test)
            _state["best_model_name"] = _state["metrics_df"].iloc[0]["model"]

    logger.info("Startup complete. Best model: %s", _state["best_model_name"])
    yield


