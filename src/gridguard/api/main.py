def _parse_origins(raw: str) -> list[str]:
    if raw.strip() == "*":
        return ["*"]
    return [o.strip() for o in raw.split(",") if o.strip()]


app = FastAPI(
    title="GridGuard DMV API",
    description=(
        "Open-source ML system for forecasting solar generation and detecting underperformance "
        "in DC/Northern Virginia campus-style solar assets. "
        "Data is synthetic deterministic demo unless real telemetry is configured."
    ),
    version=__version__,
    lifespan=lifespan,
)

app.add_middleware(
    CORSMiddleware,
    allow_origins=_parse_origins(settings.allowed_origins),
    allow_methods=["GET", "POST", "OPTIONS"],
    allow_headers=["*"],
)


# ---------------------------------------------------------------------------
# Helper
# ---------------------------------------------------------------------------

def _require_data(name: str = "Data"):
    if _state["anomaly_df"] is None:
        raise HTTPException(503, f"{name} not loaded. Run 'make demo-reset && make api'.")


def _filter_by_time(df: pd.DataFrame, start: Optional[str], end: Optional[str]) -> pd.DataFrame:
    ts_col = "timestamp" if "timestamp" in df.columns else "start_time"
    if start:
        df = df[df[ts_col] >= pd.Timestamp(start)]
    if end:
        df = df[df[ts_col] <= pd.Timestamp(end)]
    return df


